/** Claves de la definición cuyo valor NO es un texto de pantalla (nombres de campo, códigos, tipos). */
const CLAVES_QUE_NO_SE_TRADUCEN = new Set([
  'valor',
  'chave',
  'nome',
  'campo',
  'tipo',
  'filtro',
  'abre',
  'grupo',
  'fichaDaMaleta',
  'operacao',
  'convertido',
  'totaisDeValor',
  'dolar',
  'guarani',
  'data',
]);

/**
 * Cambia a español los textos de una definición de informe, en el lugar. Solo cambia los textos que
 * están en la tabla; los nombres de campo y los códigos no se tocan.
 */
export function traducirDefinicion<T>(def: T, clave = ''): T {
  if (CLAVES_QUE_NO_SE_TRADUCEN.has(clave)) return def;
  if (typeof def === 'string') return (RELATORIOS_EM_ESPANHOL[def] ?? def) as T;
  if (Array.isArray(def)) {
    const lista = def as unknown[];
    for (let i = 0; i < lista.length; i++) lista[i] = traducirDefinicion(lista[i], clave);
    return def;
  }
  if (typeof def === 'object' && def !== null) {
    const o = def as Record<string, unknown>;
    for (const k of Object.keys(o)) o[k] = traducirDefinicion(o[k], k);
  }
  return def;
}
